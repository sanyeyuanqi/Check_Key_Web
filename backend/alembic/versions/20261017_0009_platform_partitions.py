def _quote(bind, identifier: str) -> str:
    return bind.dialect.identifier_preparer.quote(identifier)


def _sequence_state(bind) -> tuple[str, int, bool]:
    sequence = bind.scalar(sa.text("SELECT pg_get_serial_sequence('credentials', 'id')"))
    if not sequence:
        raise RuntimeError("Credential ID sequence is missing; platform migration cancelled")
    last_value, is_called = bind.execute(sa.text(f"SELECT last_value, is_called FROM {sequence}")).one()
    return sequence, int(last_value), bool(is_called)


def _restore_sequence(bind, last_value: int, is_called: bool) -> None:
    largest_id = bind.scalar(sa.text("SELECT MAX(id) FROM credentials"))
    if largest_id is not None and largest_id >= last_value:
        last_value, is_called = int(largest_id), True
    bind.execute(sa.text("SELECT setval(pg_get_serial_sequence('credentials', 'id'), :value, :called)"), {
        "value": last_value, "called": is_called,
    })


def _rename_indexes(bind) -> None:
    indexes = bind.execute(sa.text("""
        SELECT index_relation.relname FROM pg_index
        JOIN pg_class AS index_relation ON index_relation.oid = pg_index.indexrelid
        WHERE indrelid = 'credentials'::regclass
    """)).scalars().all()
    for name in indexes:
        op.execute(f"ALTER INDEX {_quote(bind, name)} RENAME TO {_quote(bind, name + '_v9_old')}")


def _rewire_history(bind, target: str) -> None:
    for table_name, registry_name in (
        ("validation_batch_items", "fk_batch_items_registry"),
        ("valid_key_records", "fk_valid_key_records_registry"),
    ):
        for foreign_key in sa.inspect(bind).get_foreign_keys(table_name):
            if foreign_key["constrained_columns"] == ["credential_id"]:
                op.drop_constraint(foreign_key["name"], table_name, type_="foreignkey")
        name = registry_name if target == "credential_registry" else f"{table_name}_credential_id_fkey"
        op.create_foreign_key(
            name, table_name, target, ["credential_id"], ["id"],
            **({"ondelete": "CASCADE"} if table_name == "validation_batch_items" else {}),
        )


def _verify_rows(bind, source: str) -> None:
    columns = ", ".join(_quote(bind, name) for name in COLUMNS)
    same = bind.scalar(sa.text(f"""
        SELECT NOT EXISTS (
            (SELECT {columns} FROM {_quote(bind, source)} EXCEPT ALL SELECT {columns} FROM credentials)
            UNION ALL
            (SELECT {columns} FROM credentials EXCEPT ALL SELECT {columns} FROM {_quote(bind, source)})
        )
    """))
    if not same:
        raise RuntimeError("Credential copy verification failed; platform migration cancelled")


def _check_legacy_layout(bind) -> None:
    actual = {column["name"] for column in sa.inspect(bind).get_columns("credentials")}
    if actual != set(COLUMNS):
        raise RuntimeError("Unexpected credential columns; platform migration cancelled to preserve all fields")
    mismatch = bind.scalar(sa.text("""
        SELECT EXISTS (
            SELECT 1 FROM credentials AS credential
            JOIN jsonb_each_text(CAST(:platforms AS jsonb)) AS platform(storage_type, provider)
                ON platform.storage_type = credential.storage_type
            WHERE credential.provider <> platform.provider
        )
    """), {"platforms": json.dumps(STORAGE_TYPE_PROVIDERS)})
    if mismatch:
        raise RuntimeError("Existing credential provider/type mismatch; platform migration cancelled without changing data")


